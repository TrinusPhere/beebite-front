    "while ([string]::IsNullOrWhiteSpace($EdgeAdminPassword) -or $EdgeAdminPassword -eq 'admin123' -or $EdgeAdminPassword.Length -lt 6) {",
    '    if (-not [string]::IsNullOrWhiteSpace($EdgeAdminPassword)) {',
