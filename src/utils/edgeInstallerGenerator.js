    "",
    "while ([string]::IsNullOrWhiteSpace($StoreId) -or -not ([Guid]::TryParse($StoreId, [ref]([Guid]::Empty)))) {",
    '    if (-not [string]::IsNullOrWhiteSpace($StoreId)) { Write-Warn "UUID invalido. Copie o STORE_ID exato do painel Trinusphere." }',
